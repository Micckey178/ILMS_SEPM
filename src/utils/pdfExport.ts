import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { AttendanceRecord, UniversalInventoryItem, EquipmentAsset } from '../types';

export const exportAttendancePDF = (record: AttendanceRecord, labName?: string) => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const totalStudents = record.totalStudents || record.students.length;
  const presentCount = record.presentCount ?? record.students.filter(s => s.status === 'PRESENT').length;
  const lateCount = record.lateCount ?? record.students.filter(s => s.status === 'LATE').length;
  const absentCount = record.absentCount ?? record.students.filter(s => s.status === 'ABSENT').length;
  const attendancePercentage = record.attendancePercentage ?? (totalStudents > 0 
    ? Math.round(((presentCount + lateCount) / totalStudents) * 100) 
    : 0);

  // Header Bar (Luna deep purple & lavender palette)
  doc.setFillColor(137, 97, 216); // #8961D8
  doc.rect(0, 0, 210, 24, 'F');

  doc.setFillColor(188, 160, 245); // #BCA0F5
  doc.rect(0, 24, 210, 2, 'F');

  // Title in Header
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('METROPOLITAN INSTITUTE OF TECHNOLOGY', 14, 11);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text('Integrated Laboratory Management System (ILMS) • Official Practical Attendance Record', 14, 18);

  // Document Metadata Section
  doc.setTextColor(51, 43, 64); // #332B40
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('LABORATORY ATTENDANCE ROSTER', 14, 36);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(113, 102, 125); // #71667D

  // Left Column Metadata
  doc.text(`Session: ${record.sessionTitle} (${record.courseCode})`, 14, 43);
  doc.text(`Laboratory: ${labName || record.laboratoryName || 'Academic Facility'}`, 14, 49);
  doc.text(`Practical Batch: ${record.classBatch}`, 14, 55);

  // Right Column Metadata
  doc.text(`Session Date: ${record.date}`, 130, 43);
  doc.text(`Instructor: ${record.facultyName} (${record.facultyId})`, 130, 49);
  doc.text(`Record Status: ${record.isConfirmed ? 'CONFIRMED' : 'DRAFT'}`, 130, 55);

  // Summary Stat Boxes
  doc.setFillColor(255, 248, 242); // #FFF8F2
  doc.setDrawColor(233, 221, 241); // #E9DDF1
  doc.roundedRect(14, 60, 182, 18, 3, 3, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(137, 97, 216); // Deep purple
  doc.text(`Total: ${totalStudents}`, 22, 71);

  doc.setTextColor(59, 170, 131); // Success green
  doc.text(`Present: ${presentCount}`, 65, 71);

  doc.setTextColor(231, 163, 75); // Warning orange
  doc.text(`Late: ${lateCount}`, 110, 71);

  doc.setTextColor(228, 111, 125); // Danger pink/red
  doc.text(`Absent: ${absentCount}`, 145, 71);

  doc.setTextColor(51, 43, 64);
  doc.text(`Ratio: ${attendancePercentage}%`, 175, 71);

  // Students Table
  const tableData = record.students.map((s, idx) => [
    (idx + 1).toString(),
    s.institutionId,
    s.studentName,
    s.status.toUpperCase(),
    s.checkInTime || '—',
    s.remarks || 'Verified'
  ]);

  autoTable(doc, {
    startY: 83,
    head: [['#', 'Student ID', 'Student Full Name', 'Attendance Status', 'Check-In', 'Remarks']],
    body: tableData,
    theme: 'grid',
    headStyles: {
      fillColor: [137, 97, 216],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 9
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [51, 43, 64]
    },
    alternateRowStyles: {
      fillColor: [255, 248, 242]
    },
    styles: {
      cellPadding: 2.5,
      lineColor: [233, 221, 241],
      lineWidth: 0.2
    },
    didParseCell: (data) => {
      if (data.section === 'body' && data.column.index === 3) {
        const val = data.cell.raw;
        if (val === 'PRESENT') {
          data.cell.styles.textColor = [59, 170, 131];
          data.cell.styles.fontStyle = 'bold';
        } else if (val === 'LATE') {
          data.cell.styles.textColor = [231, 163, 75];
          data.cell.styles.fontStyle = 'bold';
        } else if (val === 'ABSENT') {
          data.cell.styles.textColor = [228, 111, 125];
          data.cell.styles.fontStyle = 'bold';
        }
      }
    }
  });

  // Footer / Sign-off block
  const finalY = (doc as any).lastAutoTable?.finalY || 200;
  const signatureY = finalY + 18 > 270 ? 270 : finalY + 18;

  doc.setFontSize(8);
  doc.setTextColor(113, 102, 125);
  doc.text('This is an authentic institutional report generated by ILMS.', 14, signatureY);
  doc.text('Academic Accreditation Standard ISO/IEC 17025 Compliant.', 14, signatureY + 4);

  // Signatures
  doc.setDrawColor(200, 200, 200);
  doc.line(130, signatureY + 6, 195, signatureY + 6);
  doc.text('Faculty / Instructor Signature', 130, signatureY + 10);

  // Save the PDF file
  const filename = `Attendance_${record.courseCode}_${record.date}.pdf`;
  doc.save(filename);
};

export const exportAuditReportPDF = (
  reportTitle: string,
  facilityName: string,
  summaryMetrics: { label: string; value: string }[],
  tableHeaders: string[],
  tableRows: string[][]
) => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  // Header
  doc.setFillColor(137, 97, 216);
  doc.rect(0, 0, 210, 22, 'F');
  doc.setFillColor(188, 160, 245);
  doc.rect(0, 22, 210, 2, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('METROPOLITAN INSTITUTE OF TECHNOLOGY • ILMS AUDIT', 14, 11);
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.text(`Official Academic Laboratory Report • Generated ${new Date().toLocaleString()}`, 14, 17);

  // Report Title
  doc.setTextColor(51, 43, 64);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text(reportTitle.toUpperCase(), 14, 34);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(113, 102, 125);
  doc.text(`Active Facility: ${facilityName}`, 14, 40);

  // Metrics Box
  doc.setFillColor(255, 248, 242);
  doc.setDrawColor(233, 221, 241);
  doc.roundedRect(14, 45, 182, 16, 2.5, 2.5, 'FD');

  const startX = 20;
  const colWidth = 170 / summaryMetrics.length;
  summaryMetrics.forEach((metric, idx) => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(113, 102, 125);
    doc.text(metric.label.toUpperCase(), startX + idx * colWidth, 51);

    doc.setFontSize(10);
    doc.setTextColor(137, 97, 216);
    doc.text(metric.value, startX + idx * colWidth, 57);
  });

  // Table
  autoTable(doc, {
    startY: 66,
    head: [tableHeaders],
    body: tableRows,
    theme: 'grid',
    headStyles: {
      fillColor: [137, 97, 216],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [51, 43, 64]
    },
    alternateRowStyles: {
      fillColor: [255, 248, 242]
    },
    styles: {
      cellPadding: 2.5,
      lineColor: [233, 221, 241],
      lineWidth: 0.2
    }
  });

  doc.save(`${reportTitle.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.pdf`);
};
